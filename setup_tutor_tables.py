
import getpass
import oracledb

def main():
    password = getpass.getpass("Enter LEARNPATH database password: ")

    connection = None
    cursor = None

    tables = [
        """
        CREATE TABLE TUTOR (
            tutor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tutor_name VARCHAR2(100) NOT NULL,
            email VARCHAR2(150) UNIQUE NOT NULL,
            subject_id NUMBER NOT NULL,
            language VARCHAR2(50) DEFAULT 'English' NOT NULL,
            experience_years NUMBER DEFAULT 0 NOT NULL,
            hourly_rate NUMBER(10,2),
            bio VARCHAR2(500),
            CONSTRAINT fk_tutor_subject
                FOREIGN KEY (subject_id) REFERENCES SUBJECT(subject_id),
            CONSTRAINT chk_tutor_experience
                CHECK (experience_years >= 0),
            CONSTRAINT chk_tutor_rate
                CHECK (hourly_rate IS NULL OR hourly_rate >= 0)
        )
        """,
        """
        CREATE TABLE TUTOR_AVAILABILITY (
            availability_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tutor_id NUMBER NOT NULL,
            session_start TIMESTAMP NOT NULL,
            session_end TIMESTAMP NOT NULL,
            status VARCHAR2(20) DEFAULT 'Available' NOT NULL,
            CONSTRAINT fk_availability_tutor
                FOREIGN KEY (tutor_id) REFERENCES TUTOR(tutor_id),
            CONSTRAINT chk_availability_status
                CHECK (status IN ('Available', 'Booked', 'Cancelled')),
            CONSTRAINT chk_availability_time
                CHECK (session_end > session_start)
        )
        """,
        """
        CREATE TABLE TUTOR_BOOKING (
            booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id NUMBER NOT NULL,
            availability_id NUMBER NOT NULL UNIQUE,
            booking_status VARCHAR2(20) DEFAULT 'Confirmed' NOT NULL,
            booked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT fk_booking_student
                FOREIGN KEY (student_id) REFERENCES STUDENT(student_id),
            CONSTRAINT fk_booking_availability
                FOREIGN KEY (availability_id)
                REFERENCES TUTOR_AVAILABILITY(availability_id),
            CONSTRAINT chk_booking_status
                CHECK (booking_status IN ('Confirmed', 'Cancelled', 'Completed'))
        )
        """
    ]

    connection = None
    cursor = None

    try:
        connection = oracledb.connect(
            user="LEARNPATH",
            password=password,
            host="127.0.0.1",
            port=1521,
            service_name="FREEPDB1"
        )
        cursor = connection.cursor()

        for statement in tables:
            table_name = statement.strip().split()[2].upper()

            cursor.execute(
                "SELECT COUNT(*) FROM user_tables WHERE table_name = :name",
                name=table_name
            )

            if cursor.fetchone()[0] > 0:
                print(f"Skipping {table_name}: already exists.")
                continue

            cursor.execute(statement)
            connection.commit()
            print(f"Created table: {table_name}")

        print("\nTutor table setup completed.")

    except oracledb.Error as error:
        if connection:
            connection.rollback()
        print("\nOracle database error:", error)
        print("Check the error before rerunning the script.")

    finally:
        if cursor:
            cursor.close()
        if connection:
            connection.close()


if __name__ == "__main__":
    main()
