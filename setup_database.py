
import getpass
import oracledb

password = getpass.getpass("Enter LEARNPATH database password: ")

connection = oracledb.connect(
    user="LEARNPATH",
    password=password,
    host="127.0.0.1",
    port=1521,
    service_name="FREEPDB1"
)

cursor = connection.cursor()

tables = [
    """
    CREATE TABLE STUDENT (
        student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_name VARCHAR2(100) NOT NULL,
        email VARCHAR2(150) UNIQUE NOT NULL,
        preferred_language VARCHAR2(50) DEFAULT 'English'
    )
    """,
    """
    CREATE TABLE SUBJECT (
        subject_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        subject_name VARCHAR2(100) NOT NULL UNIQUE,
        description VARCHAR2(500)
    )
    """,
    """
    CREATE TABLE TOPIC (
        topic_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        subject_id NUMBER NOT NULL,
        topic_name VARCHAR2(150) NOT NULL,
        difficulty VARCHAR2(20),
        sequence_no NUMBER NOT NULL,
        CONSTRAINT fk_topic_subject
            FOREIGN KEY (subject_id)
            REFERENCES SUBJECT(subject_id),
        CONSTRAINT uq_topic_sequence
            UNIQUE (subject_id, sequence_no),
        CONSTRAINT chk_topic_difficulty
            CHECK (difficulty IN ('Beginner', 'Intermediate', 'Advanced'))
    )
    """,
    """
    CREATE TABLE LEARNING_RESOURCE (
        resource_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        topic_id NUMBER NOT NULL,
        title VARCHAR2(200) NOT NULL,
        video_url VARCHAR2(500) NOT NULL,
        language VARCHAR2(50) DEFAULT 'English',
        sequence_no NUMBER DEFAULT 1 NOT NULL,
        CONSTRAINT fk_resource_topic
            FOREIGN KEY (topic_id)
            REFERENCES TOPIC(topic_id)
    )
    """,
    """
    CREATE TABLE STUDENT_PROGRESS (
        progress_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id NUMBER NOT NULL,
        topic_id NUMBER NOT NULL,
        completion_status VARCHAR2(20) DEFAULT 'Not Started',
        feedback VARCHAR2(500),
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT fk_progress_student
            FOREIGN KEY (student_id)
            REFERENCES STUDENT(student_id),
        CONSTRAINT fk_progress_topic
            FOREIGN KEY (topic_id)
            REFERENCES TOPIC(topic_id),
        CONSTRAINT uq_student_topic
            UNIQUE (student_id, topic_id),
        CONSTRAINT chk_progress_status
            CHECK (completion_status IN
                ('Not Started', 'In Progress', 'Completed'))
    )
    """
]

try:
    existing_tables = {
        "STUDENT",
        "SUBJECT",
        "TOPIC",
    }

    for index, statement in enumerate(tables, start=1):
        # Extract the table name from CREATE TABLE statement
        table_name = statement.strip().split()[2].upper()

        if table_name in existing_tables:
            print(f"Skipping {table_name}: table already exists.")
            continue

        try:
            cursor.execute(statement)
            connection.commit()
            print(f"Created table: {table_name}")

        except oracledb.DatabaseError as error:
            print(f"Error creating table {table_name}: {error}")
            raise

    print("Database setup completed successfully!")

except oracledb.DatabaseError as error:
    connection.rollback()
    print("Database error:", error)

finally:
    cursor.close()
    connection.close()
