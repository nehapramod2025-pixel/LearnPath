
CREATE TABLE TUTOR_REVIEW (
    REVIEW_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID NUMBER NOT NULL,
    TUTOR_ID NUMBER NOT NULL,
    BOOKING_ID NUMBER,
    OVERALL_RATING NUMBER(1) NOT NULL,
    ON_TIME_RATING NUMBER(1) NOT NULL,
    DOUBT_CLEARING_RATING NUMBER(1) NOT NULL,
    HELPFULNESS_RATING NUMBER(1) NOT NULL,
    FEEDBACK VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_TUTOR_REVIEW
        PRIMARY KEY (REVIEW_ID),

    CONSTRAINT FK_REVIEW_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENT(STUDENT_ID),

    CONSTRAINT FK_REVIEW_TUTOR
        FOREIGN KEY (TUTOR_ID)
        REFERENCES TUTOR(TUTOR_ID),

    CONSTRAINT FK_REVIEW_BOOKING
        FOREIGN KEY (BOOKING_ID)
        REFERENCES TUTOR_BOOKING(BOOKING_ID),

    CONSTRAINT CHK_REVIEW_OVERALL
        CHECK (OVERALL_RATING BETWEEN 1 AND 5),

    CONSTRAINT CHK_REVIEW_ONTIME
        CHECK (ON_TIME_RATING BETWEEN 1 AND 5),

    CONSTRAINT CHK_REVIEW_DOUBTS
        CHECK (DOUBT_CLEARING_RATING BETWEEN 1 AND 5),

    CONSTRAINT CHK_REVIEW_HELPFUL
        CHECK (HELPFULNESS_RATING BETWEEN 1 AND 5),

    CONSTRAINT UQ_REVIEW_STUDENT_BOOKING
        UNIQUE (STUDENT_ID, BOOKING_ID)
);
